// Writes src/lessons/meta.ts: the part of every lesson that lists and the search need, so they work before any lesson is downloaded.
// Run with `npm run gen` after adding a lesson or changing a title, level, difficulty, blurb or time. A test fails if it is stale.
import { writeFileSync } from 'node:fs'
import { createServer } from 'vite'

const server = await createServer({ configFile: false, server: { middlewareMode: true, ws: false }, appType: 'custom', logLevel: 'error', optimizeDeps: { noDiscovery: true } })
try {
  const { LESSONS, metaOf } = await server.ssrLoadModule('/src/lessons/all.ts')
  const q = s => "'" + s.replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'"
  const pair = l => `[${q(l[0])}, ${q(l[1])}]`
  const rows = metaOf(LESSONS).map(m => `  { id: ${q(m.id)}, title: ${pair(m.title)}, level: ${q(m.level)}, cat: ${q(m.cat)}, diff: ${m.diff}, time: ${q(m.time)},\n    blurb: ${pair(m.blurb)} },`)
  writeFileSync(new URL('../src/lessons/meta.ts', import.meta.url), `// Generated by scripts/gen-meta.mjs (npm run gen). Do not edit.
import type { Meta } from './extras'

/** Every lesson in learning order: what lists and the search show before the lesson itself is downloaded. */
export const META: Meta[] = [
${rows.join('\n')}
]

export const META_BY_ID = new Map(META.map(m => [m.id, m]))
`)
  console.log(`meta.ts: ${rows.length} lessons`)
} finally {
  await server.close()
}
